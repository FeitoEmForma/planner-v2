import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {readFileSync} from 'node:fs';
const require=createRequire(import.meta.url);
const parser=require('./pedido-assistente-parser.js');
const example=`Olá, Feito em Forma! Gostaria de solicitar um orçamento.\nCliente: Kethyleen\nTelefone: 11958108697\nProdutos selecionados:\n1. Calendário do Advento de Natal �\nQuantidade: 1\nValor unitário: R$ 120,00\nSubtotal: R$ 120,00\nMedidas: 5cm x 10cm\n2. Placa Welcome Grinch\nQuantidade: 1\nValor unitário: R$ 30,00\nSubtotal: R$ 30,00\nMedidas: 20 × 15 cm\n3. Enfeite Ho Ho Ho\nQuantidade: 1\nValor unitário: R$ 15,00\nSubtotal: R$ 15,00\nMedidas: 20 × 13 cm\nTotal estimado: R$ 165,00\nObservações: Nenhuma\nPodem confirmar disponibilidade?`;
const p=parser.parse(example);
assert.equal(p.client,'Kethyleen');
assert.equal(p.phone,'11958108697');
assert.equal(p.items.length,3);
assert.deepEqual(p.items.map(i=>i.unitPrice),[120,30,15]);
assert.equal(p.items[0].name,'Calendário do Advento de Natal');
assert.equal(p.items[0].measures,'5cm x 10cm');
assert.equal(p.computedTotal,165);
assert.equal(p.discrepancy,false);
assert.equal(parser.similarity('Calendário do Advento de Natal 🎄','Calendario do Advento de Natal'),100);
assert.equal(parser.price('R$ 1.234,56'),1234.56);
assert.equal(parser.price('R$ 75,00'),75);
assert.equal(parser.price('-100,00'),null);
assert.equal(parser.parse(example.replace('R$ 165,00','R$ 150,00')).discrepancy,true);
assert.ok(parser.parse(example.replace('Quantidade: 1','Quantidade: banana')).items[0].errors.length);
assert.equal(parser.parse('Cliente: Marcos\nProdutos selecionados:\n1. Chaveiro\nQuantidade: 2\nSubtotal: R$ 15,00').items[0].unitPrice,7.5);
assert.equal(parser.parse('Olá, bom dia!').items.length,0);
assert.throws(()=>parser.parse('x'.repeat(15001)));
const app=readFileSync('./app.js','utf8');
const html=readFileSync('./index.html','utf8');
const sw=readFileSync('./service-worker.js','utf8');
assert.match(app,/assistantSave:\s*async draft/);
assert.match(app,/await withWrite\(\(\)=>writeQuote\(candidate\)\)/);
assert.match(html,/id="assistantWorkspace"/);
assert.match(html,/id="assistantMessageForm"/);
assert.match(sw,/pedido-assistente\.js/);
console.log('OK: parser de pedidos, campos, medidas, moeda, divergências e integração com Supabase.');
